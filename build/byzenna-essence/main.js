function App() {
    const [page, setPage] = useState(window.location.hash.replace('#', '') || 'home');
    const [menuOpen, setMenuOpen] = useState(false);
    const [searchOpen, setSearchOpen] = useState(false);
    const [query, setQuery] = useState('');
    const [cart, setCart] = useState(() => load(KEY.cart, []));
    const [wishlist, setWishlist] = useState(() => load(KEY.wishlist, []));
    const [orders, setOrders] = useState(() => load(KEY.orders, []));
    const [profile, setProfile] = useState(() => load(KEY.profile, { name: '', email: '', phone: '', address: '' }));
    const [selectedProduct, setSelectedProduct] = useState(null);
    const [category, setCategory] = useState('all');
    const [brand, setBrand] = useState('all');
    const [sort, setSort] = useState('featured');
    const [priceMax, setPriceMax] = useState(5000);
    const [cartOpen, setCartOpen] = useState(false);
    const [notice, setNotice] = useState('');
    useEffect(() => { const onHash = () => setPage(window.location.hash.replace('#', '') || 'home'); window.addEventListener('hashchange', onHash); return () => window.removeEventListener('hashchange', onHash); }, []);
    useEffect(() => save(KEY.cart, cart), [cart]);
    useEffect(() => save(KEY.wishlist, wishlist), [wishlist]);
    useEffect(() => save(KEY.orders, orders), [orders]);
    useEffect(() => save(KEY.profile, profile), [profile]);
    const go = (p) => { window.location.hash = p; setMenuOpen(false); window.scrollTo({ top: 0, behavior: 'smooth' }); };
    const toast = (msg) => { setNotice(msg); setTimeout(() => setNotice(''), 2600); };
    const addToCart = (product, size = '100ml') => {
        const price = product.sizePrices?.[size] || product.price;
        setCart(items => { const found = items.find(i => i.id === product.id && i.size === size); return found ? items.map(i => i.id === product.id && i.size === size ? { ...i, qty: i.qty + 1 } : i) : [...items, { id: product.id, name: product.name, image: product.image, size, price, qty: 1 }]; });
        toast(`${product.name} added to your bag`);
    };
    const updateQty = (id, size, delta) => setCart(items => items.map(i => i.id === id && i.size === size ? { ...i, qty: i.qty + delta } : i).filter(i => i.qty > 0));
    const remove = (id, size) => setCart(items => items.filter(i => !(i.id === id && i.size === size)));
    const toggleWish = (id) => setWishlist(w => w.includes(id) ? w.filter(x => x !== id) : [...w, id]);
    const cartCount = cart.reduce((s, i) => s + i.qty, 0), subtotal = cart.reduce((s, i) => s + i.price * i.qty, 0);
    const filtered = useMemo(() => {
        let list = products.filter(p => (category === 'all' || p.gender === category) && (brand === 'all' || p.name.toLowerCase().includes(brand)) && p.price <= priceMax && (!query || `${p.name} ${p.category}`.toLowerCase().includes(query.toLowerCase())));
        if (sort === 'price-low')
            list = [...list].sort((a, b) => a.price - b.price);
        if (sort === 'price-high')
            list = [...list].sort((a, b) => b.price - a.price);
        if (sort === 'name')
            list = [...list].sort((a, b) => a.name.localeCompare(b.name));
        return list;
    }, [category, brand, priceMax, query, sort]);
    const openProduct = (p) => { setSelectedProduct(p); go('product'); };
    const featured = products.slice(0, 5);
    return React.createElement("div", { className: "site" },
        React.createElement("header", { className: "header" },
            React.createElement("div", { className: "header-inner" },
                React.createElement(IconButton, { className: "mobile-menu", label: "Open menu", onClick: () => setMenuOpen(true) },
                    React.createElement(Menu, null)),
                React.createElement(Logo, null),
                React.createElement("nav", { className: `main-nav ${menuOpen ? 'open' : ''}` },
                    React.createElement(IconButton, { className: "nav-close", label: "Close menu", onClick: () => setMenuOpen(false) },
                        React.createElement(X, null)),
                    [['home', 'Home'], ['shop', 'Shop'], ['brands', 'Brands'], ['about', 'About Us'], ['contact', 'Contact']].map(([id, label]) => React.createElement("a", { key: id, className: page === id ? 'active' : '', href: `#${id}`, onClick: () => setMenuOpen(false) }, label))),
                React.createElement("div", { className: "header-actions" },
                    React.createElement(IconButton, { label: "Search", onClick: () => setSearchOpen(v => !v) },
                        React.createElement(Search, null)),
                    React.createElement(IconButton, { className: "desktop-only", label: "Account", onClick: () => go('account') },
                        React.createElement(UserRound, null)),
                    React.createElement(IconButton, { label: "Wishlist", onClick: () => go('wishlist') },
                        React.createElement(Heart, null)),
                    React.createElement("button", { className: "icon-button cart-button", "aria-label": "Shopping bag", onClick: () => setCartOpen(true) },
                        React.createElement(ShoppingBag, null),
                        React.createElement("span", null, cartCount)))),
            searchOpen && React.createElement("div", { className: "search-row" },
                React.createElement("div", { className: "search-box" },
                    React.createElement(Search, null),
                    React.createElement("input", { autoFocus: true, value: query, onChange: e => setQuery(e.target.value), onKeyDown: e => e.key === 'Enter' && go('shop'), placeholder: "Search fragrances, brands or collections..." }),
                    React.createElement(IconButton, { label: "Close search", onClick: () => { setQuery(''); setSearchOpen(false); } },
                        React.createElement(X, null))))),
        menuOpen && React.createElement("div", { className: "overlay", onClick: () => setMenuOpen(false) }),
        page === 'home' && React.createElement(HomePage, { go: go, featured: featured, setCategory: setCategory, openProduct: openProduct, addToCart: addToCart, wishlist: wishlist, toggleWish: toggleWish }),
        page === 'shop' && React.createElement(ShopPage, { filtered: filtered, category: category, setCategory: setCategory, brand: brand, setBrand: setBrand, sort: sort, setSort: setSort, priceMax: priceMax, setPriceMax: setPriceMax, openProduct: openProduct, addToCart: addToCart, wishlist: wishlist, toggleWish: toggleWish }),
        page === 'product' && selectedProduct && React.createElement(ProductPage, { product: selectedProduct, addToCart: addToCart, wishlist: wishlist, toggleWish: toggleWish, go: go, openProduct: openProduct }),
        page === 'product' && !selectedProduct && React.createElement(ShopPage, { filtered: filtered, category: category, setCategory: setCategory, brand: brand, setBrand: setBrand, sort: sort, setSort: setSort, priceMax: priceMax, setPriceMax: setPriceMax, openProduct: openProduct, addToCart: addToCart, wishlist: wishlist, toggleWish: toggleWish }),
        page === 'brands' && React.createElement(BrandsPage, { go: go, openProduct: openProduct }),
        page === 'about' && React.createElement(AboutPage, { go: go }),
        page === 'contact' && React.createElement(ContactPage, { profile: profile, setProfile: setProfile, toast: toast }),
        page === 'wishlist' && React.createElement(WishlistPage, { wishlist: wishlist, products: products, toggleWish: toggleWish, openProduct: openProduct, addToCart: addToCart }),
        page === 'account' && React.createElement(AccountPage, { profile: profile, setProfile: setProfile, orders: orders, go: go, toast: toast }),
        page === 'checkout' && React.createElement(CheckoutPage, { cart: cart, subtotal: subtotal, profile: profile, setProfile: setProfile, setCart: setCart, orders: orders, setOrders: setOrders, go: go, toast: toast }),
        React.createElement(Footer, { go: go }),
        cartOpen && React.createElement(CartDrawer, { cart: cart, subtotal: subtotal, setCart: setCart, updateQty: updateQty, remove: remove, go: go, close: () => setCartOpen(false) }),
        notice && React.createElement("div", { className: "toast" },
            React.createElement(CheckCircle2, { size: 17 }),
            notice));
}
